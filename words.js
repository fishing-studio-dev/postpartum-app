export const POOLS = Object.freeze({wife: WIFE_WORDS, husband: HUSBAND_WORDS});

function gcd(a, b) { while (b) [a, b] = [b, a % b]; return a; }
// 固定の並べかえ：i → (a·i + c) mod n（a と n は互いに素なので必ず1対1）。
export function permutation(n) {
  if (n <= 1) return n === 1 ? [0] : [];
  let a = Math.max(1, Math.round(n * 0.382));
  while (gcd(a, n) !== 1) a++;
  const c = 7 % n;
  return Array.from({length: n}, (_, i) => (a * i + c) % n);
}
// 端末の日付（'YYYY-MM-DD'）を通し番号に。
export function dayNumber(date) {
  const p = parseDate(date);
  return p ? Math.floor(Date.UTC(p.y, p.m - 1, p.d) / 86400000) : 0;
}
const PERMS = new Map();
export function wordIndex(date, n) {
  if (!PERMS.has(n)) PERMS.set(n, permutation(n));
  const perm = PERMS.get(n);
  return perm[((dayNumber(date) % n) + n) % n];
}
export function fillWords(text, ctx) {
  const c = ctx || {};
  return String(text).replace(/\{(wife|husband|big|baby|daytext)\}/g, (_, k) => (c[k] == null ? '' : String(c[k])));
}
// role: 'wife' | 'husband'。役割が分からないときは null。
export function dailyWord(role, date, ctx) {
  const pool = POOLS[role];
  if (!pool) return null;
  return fillWords(pool[wordIndex(date, pool.length)], ctx);
}
